'use strict';
const assert=require('node:assert/strict'),{analyze,profits}=require('../planner.js'),position=require('../app.js');
const data=require('../tests/fixtures/nvda-history.json');
const s={risk:500,entry:130,stop:124,side:'long',cap:70,feeIn:.05,feeOut:.05,slip:0,reserve:0,step:0,platformMax:20};
const r=position(s),a=analyze(data,'2026-11-20',130,124,'long');
assert.ok(a.lastDate<'2026-11-20');assert.ok(a.mas.every(m=>m.value===null||Number.isFinite(m.value)));
const poisoned={...data,bars:[...data.bars,{date:'2099-01-01',open:1,high:1e8,low:1,close:1e8}]};
assert.deepEqual(analyze(poisoned,'2026-11-20',130,124,'long'),a,'future prices must not affect results');
assert.equal(a.mas.length,4);assert.equal(a.targets.length<=3,true);assert.ok(a.targets.every(x=>x.r>=1));
assert.throws(()=>analyze(data,'2020-01-01',130,124,'long'));
const plan=profits(s,r,[{price:'142',percent:'25'},{price:'146',percent:'25'},{price:'152',percent:'25'}]);
assert.equal(plan.remaining,.25);assert.ok(plan.net>0);assert.equal(plan.rows[0].r,2);assert.ok(plan.netIfStop<plan.net);
assert.throws(()=>profits(s,r,[{price:142,percent:70},{price:146,percent:40}]));
assert.throws(()=>profits(s,r,[{price:129,percent:25}]));
assert.throws(()=>profits(s,r,[{price:146,percent:25},{price:142,percent:25}]));
const short=profits({...s,side:'short',stop:136},position({...s,side:'short',stop:136}),[{price:118,percent:50}]);assert.equal(short.rows[0].r,2);assert.ok(short.net>0);
const sparse=profits(s,r,[{price:'',percent:''},{price:142,percent:25}]);assert.equal(sparse.total,25);
assert.ok(Math.abs(profits(s,r,[{price:142,percent:100}]).remaining)<1e-8);
console.log('PASS: cutoff/no-lookahead, SMA, candidates, long/short, fees, partial exits, invalid percentages/order, blank rows.');
console.log('NVDA before 2026-11-20:',a.lastDate,a.mas,a.targets.map(z=>({price:z.target,R:z.r,labels:z.labels})));
